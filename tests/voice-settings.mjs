import { chromium } from '@playwright/test';
import assert from 'node:assert/strict';
const browser = await chromium.launch({ headless: true, args: ['--autoplay-policy=no-user-gesture-required', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 960 } });
const failures = [];
page.on('pageerror', error => failures.push(error.message));
try {
  await page.addInitScript(() => {
    if (!localStorage.getItem('mira-preferences')) localStorage.setItem('mira-preferences', JSON.stringify({ speech: 'native', voice: 'Microsoft Huihui Desktop', volume: 0.7, rate: 0 }));
  });
  await page.goto(process.env.TEST_URL || 'http://127.0.0.1:5180');
  await page.locator('.avatar[data-ready="true"]').waitFor({ timeout: 60000 });
  await page.getByRole('button', { name: '连接与偏好设置', exact: true }).click();
  const dialog = page.locator('dialog[open]');
  const engine = dialog.getByLabel('语音引擎', { exact: true });
  const voice = dialog.getByLabel('声音', { exact: true });
  assert.equal(await engine.inputValue(), 'edge');
  assert.equal(await voice.inputValue(), 'zh-CN-XiaoxiaoNeural');
  assert.equal(await voice.locator('option').count(), 6);
  await voice.selectOption('zh-CN-XiaoyiNeural');
  await dialog.getByLabel('语速', { exact: false }).fill('2');
  await page.reload();
  await page.getByRole('button', { name: '连接与偏好设置', exact: true }).click();
  assert.equal(await voice.inputValue(), 'zh-CN-XiaoyiNeural');
  assert.equal(await dialog.getByLabel('语速', { exact: false }).inputValue(), '2');
  const requestPromise = page.waitForRequest(req => req.url().endsWith('/api/speech'));
  await dialog.getByRole('button', { name: '试听声音', exact: true }).click();
  const request = await requestPromise;
  assert.deepEqual({ engine: request.postDataJSON().engine, voice: request.postDataJSON().voice, rate: request.postDataJSON().rate }, { engine: 'edge', voice: 'zh-CN-XiaoyiNeural', rate: 2 });
  await page.waitForFunction(() => document.querySelector('.character-status')?.textContent === '正在说话', undefined, { timeout: 65000 });
  await page.waitForFunction(() => Number(document.querySelector('.avatar').dataset.mouth) > 0.04);
  await dialog.getByRole('button', { name: '停止试听', exact: true }).click();
  await page.waitForFunction(() => Number(document.querySelector('.avatar').dataset.mouth) < 0.01);
  await page.screenshot({ path: 'artifacts/edge-tts-settings.png' });
  await engine.selectOption('native');
  await page.waitForFunction(() => [...document.querySelectorAll('dialog option')].some(option => option.textContent.includes('Microsoft Huihui')));
  await page.reload();
  await page.getByRole('button', { name: '连接与偏好设置', exact: true }).click();
  assert.equal(await engine.inputValue(), 'native', 'Explicit choice must survive reload after migration');
  await engine.selectOption('edge');
  assert.equal(await voice.inputValue(), 'zh-CN-XiaoxiaoNeural');
  await page.route('**/api/speech', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'Edge-TTS 测试：网络不可用' }) }));
  await dialog.getByRole('button', { name: '试听声音', exact: true }).click();
  await dialog.getByRole('alert').filter({ hasText: '网络不可用' }).waitFor();
  assert.equal(await engine.inputValue(), 'edge', 'Failure must not silently change engine');
  await page.unroute('**/api/speech');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'artifacts/edge-tts-mobile-settings.png' });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.deepEqual(failures, []);
  console.log('Passed: old-default migration, six voices, persistent selection/rate, real Xiaoyi audio/lipsync, preview stop, explicit offline choice, visible network failure, mobile settings.');
} finally { await browser.close(); }
